  if (!cantonItem) return null;
  const dta = String(cantonItem.codigoDta || '');

  if (GOBIERNOS_LOCALES_DB[dta]) {
    return GOBIERNOS_LOCALES_DB[dta];
  }

  // Generador estandarizado con base en la división territorial oficial
  const idNum = Number(cantonItem.id) || 1;
  const provId = Number(cantonItem.provinciaId) || (provinciaObj ? Number(provinciaObj.id) : 6);
  const poblacionEst = Math.round(16000 + (idNum * 3200) + (provId * 3800));
  const presupuestoEst = Math.round(3800 + (idNum * 410) + (provId * 320));

